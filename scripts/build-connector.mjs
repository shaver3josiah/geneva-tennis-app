/**
 * Builds src/tennis/connectorSource.js (+ .d.ts) from sheets-connector/Code.gs, so the app can
 * show the coach the exact script to paste. Run: npm run connector
 *
 * CONNECTOR_VERSION is the `const VERSION = n;` line in Code.gs: bump it there when you change
 * the script (ping reports it, the app compares it with this export).
 */
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('sheets-connector/Code.gs', root), 'utf8').replace(/\r\n/g, '\n');
const version = /^const VERSION = (\d+);/m.exec(source);
if (!version) throw new Error('Code.gs has no "const VERSION = <integer>;" line');

writeFileSync(
  new URL('src/tennis/connectorSource.js', root),
  [
    '// GENERATED by scripts/build-connector.mjs from sheets-connector/Code.gs. Do not edit; run `npm run connector`.',
    `export const CONNECTOR_VERSION = ${Number(version[1])};`,
    `export const CONNECTOR_SOURCE = ${JSON.stringify(source)};`,
    '',
  ].join('\n')
);
writeFileSync(
  new URL('src/tennis/connectorSource.d.ts', root),
  [
    '// GENERATED by scripts/build-connector.mjs.',
    '/** The Apps Script the coach pastes (sheets-connector/Code.gs). */',
    'export declare const CONNECTOR_SOURCE: string;',
    '/** Bumped with `const VERSION` in Code.gs; the connector reports it on ping. */',
    'export declare const CONNECTOR_VERSION: number;',
    '',
  ].join('\n')
);
console.log(`connectorSource.js: version ${version[1]}, ${source.length} characters`);
