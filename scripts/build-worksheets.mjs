/**
 * Bakes scripts/worksheets/*.html into src/worksheets.generated.ts.
 *
 * WHY THE APP CARRIES ITS OWN COPY. Everything else in the Locker is a Firestore
 * document the coach publishes. A worksheet that ships with the binary is there the
 * first time the app opens, on a phone with no signal, and without anyone having to
 * write a document by hand — which is the only way this one would otherwise arrive,
 * since nothing in the app uploads a workflow and `npm run seed` only ever writes to
 * the local emulator.
 *
 * The HTML file stays the source of truth: it opens in a browser by double-clicking,
 * and this script is the only thing that copies it. Run `npm run worksheets` after
 * editing one; `npm run check:worksheets` fails if the generated file has drifted,
 * which is what CI runs.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, 'worksheets');
const OUT = join(HERE, '..', 'src', 'worksheets.generated.ts');

/** id and cadence per file. Anything not listed here is not shipped. */
const SHIPPED = {
  'match-tracker.html': { id: 'builtin-match-tracker', name: 'Match Tracker', cadence: 'daily' },
};

/**
 * A worksheet that is a COPY of a file whose one home is somewhere else (a sibling repo,
 * say) is listed here so the two cannot drift unseen. Nothing is mirrored today:
 * match-tracker.html is built from this repo's own tracker/ sources by
 * scripts/build-tracker.mjs, so it has no other home to fall behind.
 *
 * The guard stays for the next one. On a machine that has both repos side by side,
 * `npm run worksheets` re-copies the source before generating, and `--check` FAILS when
 * the copy has fallen behind it. CI checks out only this repo, so the source is absent
 * there and both steps skip: what CI verifies is that the committed HTML and the generated
 * file agree, which is the half it can see.
 */
const MIRROR = [];

/** Returns [] when in sync or when the source is not on this machine. */
function mirrorDrift({ write }) {
  const stale = [];
  for (const m of MIRROR) {
    if (!existsSync(m.from)) continue; // CI, or a checkout without the site repo beside it
    const src = readFileSync(m.from, 'utf8').replace(/\r\n/g, '\n');
    const dst = join(SRC, m.to);
    const cur = existsSync(dst) ? readFileSync(dst, 'utf8').replace(/\r\n/g, '\n') : '';
    if (src === cur) continue;
    if (write) {
      writeFileSync(dst, src);
      console.log(`worksheets: re-copied ${m.to} from ${m.from}`);
    } else {
      stale.push(m.to);
    }
  }
  return stale;
}

export function render() {
  const files = readdirSync(SRC).filter((f) => f.endsWith('.html') && SHIPPED[f]);
  const entries = files.map((f) => {
    // Normalise to LF before anything else looks at it. Git stores these .html files
    // with LF and hands a Windows checkout CRLF, and JSON.stringify below turns a real
    // CRLF into the four characters \r\n INSIDE the string literal. That is escape text,
    // not a line break, so the check's own line-ending normalisation cannot reach it:
    // regenerate on Windows and the file matches on Windows and fails on CI, which is
    // exactly what happened after a worksheet was renamed. Read it the same way on every
    // machine and the generated file is identical everywhere.
    const html = readFileSync(join(SRC, f), 'utf8').replace(/\r\n/g, '\n');
    const meta = SHIPPED[f];
    return (
      `  {\n` +
      `    id: ${JSON.stringify(meta.id)},\n` +
      `    name: ${JSON.stringify(meta.name)},\n` +
      `    cadence: ${JSON.stringify(meta.cadence)},\n` +
      `    sizeBytes: ${Buffer.byteLength(html, 'utf8')},\n` +
      // JSON.stringify produces a valid JS string literal, so the page's own quotes,
      // backslashes and newlines survive verbatim rather than being re-escaped by hand.
      `    html: ${JSON.stringify(html)},\n` +
      `  },`
    );
  });

  return (
    `/**\n` +
    ` * GENERATED by \`npm run worksheets\`. Do not edit: edit the HTML under\n` +
    ` * scripts/worksheets/ and run it again. \`npm run check:worksheets\` fails when\n` +
    ` * this file has drifted from those sources.\n` +
    ` */\n` +
    `import type { Workflow } from './types';\n\n` +
    `/** Worksheets that ship inside the binary, merged into the Locker beside the\n` +
    ` *  ones the coach publishes. Present offline and on first launch. */\n` +
    `export const BUILTIN_WORKFLOWS: Workflow[] = [\n` +
    entries.join('\n') +
    `\n].map((w) => ({ ...w, publishedBy: 'Geneva Tennis', publishedAt: null })) as Workflow[];\n\n` +
    `export const isBuiltin = (id: string): boolean =>\n` +
    `  BUILTIN_WORKFLOWS.some((w) => w.id === id);\n`
  );
}

const check = process.argv.includes('--check');

// Pull the mirrored sources in FIRST, so `render()` below reads what was just copied.
const stale = mirrorDrift({ write: !check });
if (stale.length) {
  console.error(
    `scripts/worksheets/${stale.join(', ')} has fallen behind the source it mirrors. ` +
      'Run: npm run worksheets'
  );
  process.exit(1);
}

const out = render();

if (check) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing counts as drifted */
  }
  if (current.replace(/\r\n/g, '\n') !== out) {
    console.error('src/worksheets.generated.ts is stale. Run: npm run worksheets');
    process.exit(1);
  }
  console.log('worksheets: generated file is current');
} else {
  writeFileSync(OUT, out);
  console.log(`worksheets: wrote ${OUT} (${Buffer.byteLength(out, 'utf8')} bytes)`);
}
